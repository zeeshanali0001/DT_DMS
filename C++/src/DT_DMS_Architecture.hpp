/// \file DT_DMS_Architecture.hpp
/// \brief A Digital Twin that connects one component of each kind of the DT-DMS framework.

#ifndef DT_DMS_ARCHITECTURE_HPP
#define DT_DMS_ARCHITECTURE_HPP

#include <memory>

#include "DT_DMS.hpp"

/// \brief The `DT_DMS_Architecture` class connects all classes of the DT-DMS framework.
///
/// It is a Digital Twin (DT_DMS) with one named component of each kind: one data source, the three types of
/// models, the five types of services and the data assimilation function. Its collaboration diagram
/// (generated by Doxygen/Graphviz) is the architecture image of the framework.
///
/// Assign the fields, then call connect() so that every component belongs to `D`, `M` or `S` and is reached by
/// `μ`. The example run is in `DT_DMS_Architecture.cpp` (`main`).
/// \tparam T the type of a datum `d ∈ D`.
template <typename T>
class DT_DMS_Architecture : public DT_DMS<T> {

 public:
  /// \brief Constructs the DT architecture.
  /// \param delta the freshness threshold `δ`.
  explicit DT_DMS_Architecture(double delta) : DT_DMS<T>(delta) { assimilation = this->mu; }

  /// \brief Adds every assigned field to the Digital Twin. Each service is coupled to a model of the matching
  /// type: monitoring and diagnosis to the descriptive model, prediction to the predictive model, optimization
  /// and control to the prescriptive model.
  void connect() {
    if (data) this->addData(data);
    if (descriptiveModel) this->addModel(descriptiveModel);
    if (predictiveModel) this->addModel(predictiveModel);
    if (prescriptiveModel) this->addModel(prescriptiveModel);
    if (monitoring) this->addService(monitoring, descriptiveModel);
    if (prediction) this->addService(prediction, predictiveModel);
    if (diagnosis) this->addService(diagnosis, descriptiveModel);
    if (optimization) this->addService(optimization, prescriptiveModel);
    if (control) this->addService(control, prescriptiveModel);
  }

#ifdef DOXYGEN_RUNNING
  // Documentation view of the fields. In the code, each field is a std::shared_ptr to the class with the type
  // argument T (e.g., std::shared_ptr<Data::DT_Data<T>>); Doxygen draws the relation to a class, with its parent
  // classes, only for this plain form (the Java version uses raw types for the same reason).

  /// The data source (`D`); in the code: `std::shared_ptr<Data::DT_Data<T>>`.
  Data::DT_Data data;

  /// The descriptive model (`M_desc`); in the code: `std::shared_ptr<Models::DT_Model_Descriptive<T>>`.
  Models::DT_Model_Descriptive descriptiveModel;
  /// The predictive model (`M_pred`); in the code: `std::shared_ptr<Models::DT_Model_Predictive<T>>`.
  Models::DT_Model_Predictive predictiveModel;
  /// The prescriptive model (`M_presc`); in the code: `std::shared_ptr<Models::DT_Model_Prescriptive<T>>`.
  Models::DT_Model_Prescriptive prescriptiveModel;

  /// The monitoring service (`S_moni`); in the code: `std::shared_ptr<Services::DT_Service_Monitoring<T>>`.
  Services::DT_Service_Monitoring monitoring;
  /// The prediction service (`S_pred`); in the code: `std::shared_ptr<Services::DT_Service_Prediction<T>>`.
  Services::DT_Service_Prediction prediction;
  /// The diagnosis service (`S_diag`); in the code: `std::shared_ptr<Services::DT_Service_Diagnosis<T>>`.
  Services::DT_Service_Diagnosis diagnosis;
  /// The optimization service (`S_opti`); in the code: `std::shared_ptr<Services::DT_Service_Optimization<T>>`.
  Services::DT_Service_Optimization optimization;
  /// The control service (`S_cont`); in the code: `std::shared_ptr<Services::DT_Service_Control<T>>`.
  Services::DT_Service_Control control;

  /// The model inference or data assimilation function (`μ`), the same object as DT_DMS::getMu(); in the code:
  /// `std::shared_ptr<Mu::DT_Mu<T>>`.
  Mu::DT_Mu assimilation;
#else
  std::shared_ptr<Data::DT_Data<T>> data;
  std::shared_ptr<Models::DT_Model_Descriptive<T>> descriptiveModel;
  std::shared_ptr<Models::DT_Model_Predictive<T>> predictiveModel;
  std::shared_ptr<Models::DT_Model_Prescriptive<T>> prescriptiveModel;
  std::shared_ptr<Services::DT_Service_Monitoring<T>> monitoring;
  std::shared_ptr<Services::DT_Service_Prediction<T>> prediction;
  std::shared_ptr<Services::DT_Service_Diagnosis<T>> diagnosis;
  std::shared_ptr<Services::DT_Service_Optimization<T>> optimization;
  std::shared_ptr<Services::DT_Service_Control<T>> control;
  std::shared_ptr<Mu::DT_Mu<T>> assimilation;
#endif
};

#endif  // DT_DMS_ARCHITECTURE_HPP
